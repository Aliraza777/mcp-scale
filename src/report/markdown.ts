import { totalSavings } from "../analyze/index.js";
import { CLIENTS } from "../clients/index.js";
import type { Report, ServerReport } from "../types.js";

const fmt = (n: number) => n.toLocaleString("en-US");

function status(s: ServerReport): string {
  if (s.config.disabled) return `off (${s.config.disabledReason ?? "disabled"})`;
  if (s.shadowedBy) return `overridden by ${s.shadowedBy}`;
  if (s.config.pendingApproval) return "awaiting approval";
  if (!s.probe) return "not measured";
  if (s.probe.status === "auth") return "needs sign-in";
  return s.probe.ok ? "ok" : s.probe.status;
}

export function renderMarkdown(report: Report): string {
  const out: string[] = [
    "# MCP context budget",
    "",
    `_Generated by [mcp-scale](https://github.com/Aliraza777/mcp-scale) · tokens ${report.tokenizer}_`,
    "",
  ];
  for (const c of report.clients) {
    const extra = c.unmeasured ? ` (+ ${c.unmeasured} not counted)` : "";
    out.push(
      `## ${CLIENTS[c.client].label}: ${fmt(c.effectiveTokens)} tokens at session start${extra}`,
      "",
    );
    for (const n of c.notes) out.push(`_${n}_`, "");
    out.push("| Server | Scope | Tools | Tokens | Status |", "|---|---|---:|---:|---|");
    for (const s of c.servers)
      out.push(
        `| ${s.config.name.replace(/\|/g, "\\|")} | ${s.config.scope} | ${s.probe?.ok ? s.tools.length : "–"} | ${s.probe?.ok ? fmt(s.effectiveTokens) : "–"} | ${status(s).replace(/\|/g, "\\|")} |`,
      );
    out.push("");
  }
  if (report.findings.length) {
    out.push("## Findings", "");
    for (const f of report.findings) out.push(`- **${f.severity}** ${f.message}`);
    out.push("");
  }
  const savings = totalSavings(report.findings);
  if (savings) out.push(`**Potential savings:** ~${fmt(savings)} tokens per session.`, "");
  return out.join("\n");
}
